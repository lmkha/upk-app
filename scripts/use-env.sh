#!/usr/bin/env bash
# Sets up one environment from secrets/<name>/, the folder handed out by the
# project owner (git-ignored):
#   - writes secrets.properties: ENVIRONMENT=<name>, then secrets/<name>/secrets.properties
#   - copies the other files listed below as they are
# The folder name is the only source of ENVIRONMENT, so the files in secrets/
# must not define it.
#
# Usage:
#   scripts/use-env.sh <dev|staging|prod>
#
# Windows uses use-env.bat. Keep the two scripts in sync.

set -euo pipefail

cd "$(dirname "$0")/.."

# Files copied as they are: "<file in secrets/<name>/>:<destination in the repository>".
# Add a line here, and in use-env.bat, when the setup needs another file.
COPIED_FILES=(
  "google-services.json:app/google-services.json"
)

fail() {
  echo "error: $*" >&2
  exit 1
}

environment="${1:-}"
case "${environment}" in
  dev | staging | prod) ;;
  *) fail "usage: scripts/use-env.sh <dev|staging|prod>" ;;
esac

[ -d secrets ] ||
  fail "secrets/ not found. Ask the project owner for it and put it in the repository root."

source_dir="secrets/${environment}"
[ -d "${source_dir}" ] || fail "${source_dir}/ not found. Ask the project owner for an updated secrets/ folder."

# Check everything before writing anything, so a failure never leaves the files
# of two environments mixed.
for name in secrets.properties "${COPIED_FILES[@]%%:*}"; do
  [ -f "${source_dir}/${name}" ] || fail "${source_dir}/${name} not found."
done
if grep -Eq '^[[:space:]]*ENVIRONMENT([[:space:]=:]|$)' "${source_dir}/secrets.properties"; then
  fail "remove the ENVIRONMENT line from ${source_dir}/secrets.properties: this script sets it from the folder name."
fi

# Remove the files of the previous environment before writing the new ones. If a
# write then fails, a file is missing and the build stops, instead of running on
# the files of two environments.
rm -f secrets.properties "${COPIED_FILES[@]#*:}"

{
  echo "# Generated by scripts/use-env.sh from ${source_dir}/. Do not edit: change that folder and run the script again."
  echo "ENVIRONMENT=${environment}"
  cat "${source_dir}/secrets.properties"
} > secrets.properties

for entry in "${COPIED_FILES[@]}"; do
  cp "${source_dir}/${entry%%:*}" "${entry#*:}"
done

echo "Environment set to '${environment}'. Sync Gradle in Android Studio before the next build."
